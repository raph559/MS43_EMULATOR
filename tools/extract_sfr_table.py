"""Generate SfrTable.g.cs from the C167CR user's manual, Table 22-4.

    python -I sim/tools/extract_sfr_table.py sim/refs/c167cr_um.txt sim/src/Ms43Sim.Core/Bus/SfrTable.g.cs

Input is the text from sim/tools/pdf_to_text.py. Table 22-4 ("C167CR Registers, Ordered by
Address") gives each register's name, physical address, area marker (E = ESFR, X = X-bus
peripheral), 8-bit short address, description and reset value. Rows can wrap over several
lines; a row ends at the line carrying its reset value.

Kept: registers in the SFR area (00'FE00-00'FFFF) and the ESFR area (00'F000-00'F1FF).
Skipped: X-bus registers (the CAN module, a RAM stub in plan 1), including the per-message
rows whose address contains 'n'.

Reset values: X and U digits (pin-dependent or undefined) become 0, for determinism. A
leading footnote marker such as "1)" is dropped.
"""
import re
import sys

# The bit-addressable marker "b" is sometimes glued to the name ("PWMCON0b FF30H").
ROW_START = re.compile(r"^(?P<name>[A-Z][A-Z0-9_]*)(?P<bit>\s*b)?\s+(?P<addr>[0-9A-Fn]{4})\s?H\b(?P<rest>.*)$")
RESET_END = re.compile(r"(?:\d\))?(?P<reset>[0-9A-FXUx]{2,4})\s?H\s*$")
NOISE = re.compile(r"^(=== page|C167CR$|Derivatives$|The Register Set|User.s Manual|Table 22-4|Name Physical|Address$|8-bit$|Addr\.$|Description Reset|Value$)")


def rows(lines):
    current = None
    for line in lines:
        line = line.strip()
        if not line or NOISE.match(line):
            continue
        start = ROW_START.match(line)
        if start and current is None:
            current = [line]
        elif current is not None:
            current.append(line)
        else:
            continue
        joined = " ".join(current)
        if RESET_END.search(joined):
            yield joined
            current = None


def parse(row):
    m = ROW_START.match(row)
    name, addr, rest = m.group("name"), m.group("addr"), m.group("rest")
    if "n" in addr:
        return None
    address = int(addr, 16)
    if not (0xF000 <= address <= 0xF1FF or 0xFE00 <= address <= 0xFFFF):
        return None
    extended = bool(re.match(r"\s*E\b", rest))
    if re.match(r"\s*X\b", rest):
        return None
    reset_text = RESET_END.search(row).group("reset")
    reset = int(re.sub("[XUx]", "0", reset_text), 16)
    return address, name, reset, bool(m.group("bit")), extended


def main(src, dst):
    with open(src, encoding="utf-8") as f:
        text = f.read().split("\n")
    first = next(i for i, l in enumerate(text) if "Table 22-4 C167CR Registers, Ordered by Address" in l)
    last = next(i for i, l in enumerate(text) if i > first and l.strip().startswith("22.5 Special Notes"))
    entries = {}
    for row in rows(text[first + 1:last]):
        parsed = parse(row)
        if parsed:
            entries[parsed[0]] = parsed
    with open(dst, "w", encoding="utf-8", newline="\n") as out:
        out.write("// <auto-generated>\n")
        out.write("// Generated by sim/tools/extract_sfr_table.py from the C167CR Derivatives User's Manual\n")
        out.write("// V3.1, Table 22-4. Reset-value digits X and U (pin-dependent or undefined) are 0 here,\n")
        out.write("// for determinism. Do not edit by hand.\n")
        out.write("// </auto-generated>\n")
        out.write("namespace Ms43Sim.Core;\n\n")
        out.write("public static partial class SfrTable\n{\n")
        out.write("    static readonly SfrInfo[] all =\n    {\n")
        for address in sorted(entries):
            a, name, reset, bit, ext = entries[address]
            out.write('        new(0x%04X, "%s", 0x%04X, %s, %s),\n'
                      % (a, name, reset, "true" if bit else "false", "true" if ext else "false"))
        out.write("    };\n}\n")
    print("%d registers" % len(entries))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
